export function buildPostalExam(questions: PostalRuleQuestion[], careerLevel: PostalCareerLevel): PostalRulesExam {
  const points = questions.length ? Math.round(100 / questions.length) : 0;
  const items = questions.map((item, index) => ({
    ...shufflePostalChoiceOptions(item),
    item_no: index + 1,
    points,
  }));
  return {
    kind: "postal_rules_exam",
    title: careerLevel === "professional_2_to_1" ? "郵政法規概要練習" : "郵政法規練習",
    career_level: careerLevel,
    total_questions: items.length,
    total_points: 100,
    items,
  };
}

function shufflePostalChoiceOptions(item: PostalRuleQuestion): PostalRuleQuestion {
  if (item.question_format !== "single_choice" || !item.options) return item;
  const keys = ["A", "B", "C", "D"] as const;
  const originalAnswerKey = item.answer.trim().toUpperCase() as (typeof keys)[number];
  const correctText = item.options[originalAnswerKey];
  if (!correctText) return item;

  const shuffledTexts = shuffle(keys.map((key) => item.options?.[key] ?? ""));
  const nextOptions = {
    A: shuffledTexts[0],
    B: shuffledTexts[1],
    C: shuffledTexts[2],
    D: shuffledTexts[3],
  };
  const nextAnswer = keys.find((key) => nextOptions[key] === correctText) ?? originalAnswerKey;

  return {
    ...item,
    options: nextOptions,
    answer: nextAnswer,
  };
}

function shuffle<T>(items: T[]) {
  return [...items].sort(() => Math.random() - 0.5);
}
