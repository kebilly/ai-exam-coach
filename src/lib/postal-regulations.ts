export function validatePostalQuestion(question: PostalRuleQuestion) {
  const errors: string[] = [];

  if (!postalLawAreas.includes(question.law_area)) errors.push("法規分類不在允許清單內。");

  if (question.question_format === "single_choice") {
    if (!question.options) {
      errors.push("單選題必須提供 A-D 四個選項。");
    } else {
      const values = Object.values(question.options).map((item) => item.trim());
      const unique = new Set(values);
      if (values.some((item) => item.length < 1)) errors.push("選項不得為空。");
      if (unique.size < 4) errors.push("選項內容不可重複。");
    }
    if (!["A", "B", "C", "D"].includes(question.answer.trim().toUpperCase())) {
      errors.push("單選題答案必須為 A、B、C 或 D。");
    }
  }

  if (question.question.length < 12) errors.push("題目過短，可能無法形成有效測驗。");
  if (question.explanation.length < 20) errors.push("解析過短，無法支撐答案。");
  if (!question.source_articles.length) errors.push("必須提供法規來源或校對註記。");

  for (const source of question.source_articles) {
    if (!postalLawAreas.includes(source.law_name)) {
      errors.push(`來源法規分類錯誤：${source.law_name}`);
    }
    if (!source.note.trim()) errors.push("來源註記不得為空。");
  }

  return errors;
}

export function getAutoReviewStatus(question: PostalRuleQuestion): PostalQuestionReviewStatus {
  return validatePostalQuestion(question).length ? "needs_edit" : "auto_reviewed";
}

