type CompactPostalQuestion = {
  career_level?: PostalCareerLevel;
  law_area: PostalLawArea;
  difficulty?: 1 | 2 | 3;
  question: string;
  correct: string;
  wrong: [string, string, string];
  explanation: string;
  article_no?: string;
  tags?: string[];
};

function compactChoice(row: CompactPostalQuestion): PostalRuleQuestion {
  return choice({
    career_level: row.career_level,
    law_area: row.law_area,
    difficulty: row.difficulty ?? 2,
    question: row.question,
    options: {
      A: row.correct,
      B: row.wrong[0],
      C: row.wrong[1],
      D: row.wrong[2],
    },
    answer: "A",
    explanation: row.explanation,
    article_no: row.article_no,
    tags: ["審題稿v2", ...(row.tags ?? [row.law_area])],
  });
}

